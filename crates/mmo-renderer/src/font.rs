use alloc::collections::BTreeMap;
use alloc::vec::Vec;
use fontdue::{Font, FontSettings, Metrics};

static UI_FONT_BYTES: &[u8] = include_bytes!("../assets/ui-font.ttf");

pub struct CachedGlyph {
    pub metrics: Metrics,
    pub bitmap: Vec<u8>,
}

pub struct TtfUiFont {
    font: Font,
    cache: BTreeMap<(char, u16), CachedGlyph>,
}

impl TtfUiFont {
    pub fn new() -> Self {
        let font = Font::from_bytes(
            UI_FONT_BYTES,
            FontSettings {
                scale: 24.0,
                ..FontSettings::default()
            },
        )
        .expect("embedded UI TTF font must be valid");
        Self {
            font,
            cache: BTreeMap::new(),
        }
    }

    #[inline]
    pub fn px_for_scale(scale: i32) -> f32 {
        match scale.max(1) {
            1 => 11.5,
            2 => 17.5,
            s => 17.5 + ((s - 2) as f32) * 6.0,
        }
    }

    #[inline]
    pub fn ascent_px(&self, scale: i32) -> i32 {
        let px = Self::px_for_scale(scale);
        if let Some(lm) = self.font.horizontal_line_metrics(px) {
            mmo_protocol::ceil_f32(lm.ascent) as i32
        } else {
            mmo_protocol::ceil_f32(px * 0.8) as i32
        }
    }

    #[inline]
    pub fn glyph(&mut self, ch: char, scale: i32) -> &CachedGlyph {
        let px = Self::px_for_scale(scale);
        let key_px = (px * 10.0) as u16;
        self.cache.entry((ch, key_px)).or_insert_with(|| {
            let (metrics, bitmap) = self.font.rasterize(ch, px);
            CachedGlyph { metrics, bitmap }
        })
    }

    pub fn measure_text(&mut self, text: &str, scale: i32) -> i32 {
        let mut total = 0.0f32;
        for ch in text.chars() {
            let advance = self.glyph(ch, scale).metrics.advance_width;
            total += advance;
        }
        mmo_protocol::ceil_f32(total) as i32
    }
}

