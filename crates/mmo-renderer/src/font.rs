#[cfg(test)]
mod tests {
    use super::{glyph_5x7, TtfUiFont};

    #[test]
    fn spanish_accents_have_distinct_glyphs_and_support_lowercase() {
        for (lower, upper, base) in [
            ('á', 'Á', 'A'),
            ('é', 'É', 'E'),
            ('í', 'Í', 'I'),
            ('ó', 'Ó', 'O'),
            ('ú', 'Ú', 'U'),
            ('ñ', 'Ñ', 'N'),
        ] {
            assert_ne!(glyph_5x7(lower), glyph_5x7(upper));
            assert_ne!(glyph_5x7(upper), glyph_5x7(base));
            assert_ne!(glyph_5x7(lower), glyph_5x7(base.to_ascii_lowercase()));
        }
    }

    #[test]
    fn ttf_font_rasterizes_spanish_glyphs_and_measures_width() {
        let mut ttf = TtfUiFont::new();
        for ch in ['A', 'g', 'á', 'é', 'í', 'ó', 'ú', 'ñ', 'Ñ', 'Á', 'É', '¡', '¿'] {
            let g = ttf.glyph(ch, 1);
            assert!(g.metrics.width > 0 && g.metrics.height > 0);
            assert!(g.bitmap.iter().any(|&a| a > 0));
        }
        assert!(ttf.measure_text("CUENTA ONLINE · TLS", 1) > 40);
        assert!(ttf.measure_text("WFO", 2) > ttf.measure_text("WFO", 1));
    }
}
